import argparse
import csv
import pickle
import re
from pathlib import Path


DEFAULT_RESULTS_DIR = Path("ignore/results")


def parse_folder_name(folder_name):
    """
    Extract agent, MLLM, and optional label from a result folder name.

    Example:
    Agent_DataMap__MLLM_gemma3_27b__small_10x1
    becomes:
    agent = DataMap
    mllm = gemma3_27b
    label = small_10x1
    """
    parts = folder_name.split("__")

    agent = "Unknown"
    mllm = "Unknown"
    extra_parts = []

    for part in parts:
        if part.startswith("Agent_"):
            agent = part.replace("Agent_", "")
        elif part.startswith("MLLM_"):
            mllm = part.replace("MLLM_", "")
        else:
            extra_parts.append(part)

    label = "__".join(extra_parts) if extra_parts else "N/A"

    return agent, mllm, label


def load_pickle(path):
    """
    Safely load a pickle file.

    Note:
    This should only be used on pickle files generated by this project.
    """
    if not path.exists():
        return None

    try:
        with open(path, "rb") as f:
            return pickle.load(f)
    except Exception as exception:
        print(f"Could not read {path}: {exception}")
        return None


def get_episode_items(episodes):
    """
    Convert saved episodes into a list of (episode_id, episode) pairs.

    episodes.p is usually a dictionary:
    {
        path_idx: episode
    }
    """
    if episodes is None:
        return []

    if isinstance(episodes, dict):
        return list(episodes.items())

    try:
        return list(enumerate(episodes))
    except Exception:
        return []


def get_value(obj, possible_names):
    """
    Try to get a value from an object or dictionary.
    """
    if obj is None:
        return None

    if isinstance(obj, dict):
        for name in possible_names:
            if name in obj:
                return obj[name]

    for name in possible_names:
        if hasattr(obj, name):
            return getattr(obj, name)

    return None


def get_point_coords(point):
    """
    Return x, y, z from a point-like object or dictionary.
    """
    if point is None:
        return "N/A", "N/A", "N/A"

    if isinstance(point, dict):
        return (
            point.get("x", "N/A"),
            point.get("y", "N/A"),
            point.get("z", "N/A"),
        )

    x = getattr(point, "x", "N/A")
    y = getattr(point, "y", "N/A")
    z = getattr(point, "z", "N/A")

    return x, y, z


def calculate_distance(point_a, point_b):
    """
    Calculate distance between two point-like objects.

    If the project's Point.distance() method exists, use it.
    Otherwise, calculate Euclidean distance from x, y, z.
    """
    if point_a is None or point_b is None:
        return "N/A"

    try:
        if hasattr(point_a, "distance"):
            return round(point_a.distance(point_b), 2)
    except Exception:
        pass

    try:
        ax, ay, az = get_point_coords(point_a)
        bx, by, bz = get_point_coords(point_b)

        ax, ay, az = float(ax), float(ay), float(az)
        bx, by, bz = float(bx), float(by), float(bz)

        distance = ((ax - bx) ** 2 + (ay - by) ** 2 + (az - bz) ** 2) ** 0.5
        return round(distance, 2)
    except Exception:
        return "N/A"


def parse_waypoint_from_response(response):
    """
    Try to parse a waypoint from an MLLM response.

    Expected format:
    [WAYPOINT]: (x, y)
    """
    if not isinstance(response, str):
        return None

    match = re.search(
        r"\[WAYPOINT\]\s*:\s*\(?\s*(-?\d+)\s*,\s*(-?\d+)\s*\)?",
        response,
        flags=re.IGNORECASE,
    )

    if not match:
        return None

    try:
        x = int(match.group(1))
        y = int(match.group(2))
        return x, y
    except Exception:
        return None


def parse_strategy_from_response(response):
    """
    Try to parse the strategy text from an MLLM response.

    Expected format:
    [STRATEGY]: reason...
    [WAYPOINT]: (x, y)
    """
    if not isinstance(response, str):
        return ""

    match = re.search(
        r"\[STRATEGY\]\s*:\s*(.*?)(?=\[WAYPOINT\]|$)",
        response,
        flags=re.IGNORECASE | re.DOTALL,
    )

    if not match:
        return ""

    return " ".join(match.group(1).strip().split())


def get_mllm_info(episode):
    """
    Extract MLLM calls, generated waypoint coordinates, and strategy text.

    In the current project, HighLevelPolicy stores MLLM responses in:
    episode.states[*]["high_level_policy_response"]
    """
    states = get_value(episode, ["states"])

    if not states:
        return {
            "n_mllm_calls": 0,
            "parsed_waypoints": [],
            "strategies": [],
            "last_response": "",
        }

    n_mllm_calls = 0
    parsed_waypoints = []
    strategies = []
    last_response = ""

    try:
        for state in states:
            if not isinstance(state, dict):
                continue

            if "high_level_policy_response" not in state:
                continue

            n_mllm_calls += 1
            response = state.get("high_level_policy_response", "")
            last_response = response

            waypoint = parse_waypoint_from_response(response)
            strategy = parse_strategy_from_response(response)

            if waypoint is not None:
                parsed_waypoints.append(waypoint)

            if strategy:
                strategies.append(strategy)

    except Exception:
        pass

    return {
        "n_mllm_calls": n_mllm_calls,
        "parsed_waypoints": parsed_waypoints,
        "strategies": strategies,
        "last_response": last_response,
    }


def summarize_episode(result_folder_name, episode_id, episode):
    """
    Create one CSV row for one episode.
    """
    agent, mllm, label = parse_folder_name(result_folder_name)

    termination = get_value(episode, ["termination"])
    success = termination == "goal_reached"

    action_history = get_value(episode, ["action_history"])
    path_history = get_value(episode, ["path_history"])
    waypoint_history = get_value(episode, ["waypoint_history"])

    n_steps = len(action_history) if action_history is not None else "N/A"
    n_path_points = len(path_history) if path_history is not None else "N/A"

    n_waypoints_from_history = 0
    if waypoint_history is not None:
        try:
            n_waypoints_from_history = len(waypoint_history)
        except Exception:
            n_waypoints_from_history = 0

    mllm_info = get_mllm_info(episode)
    parsed_waypoints = mllm_info["parsed_waypoints"]
    n_waypoints_from_response = len(parsed_waypoints)

    # Use the larger count because waypoint_history may not always be updated.
    n_waypoints = max(n_waypoints_from_history, n_waypoints_from_response)

    start_point = get_value(episode, ["start_point"])
    target_point = get_value(episode, ["target_point"])

    if path_history:
        final_point = path_history[-1]
    else:
        final_point = get_value(episode, ["point"])

    start_x, start_y, start_z = get_point_coords(start_point)
    final_x, final_y, final_z = get_point_coords(final_point)
    target_x, target_y, target_z = get_point_coords(target_point)

    final_distance_to_target = calculate_distance(final_point, target_point)

    waypoint_text = "; ".join(f"({x}, {y})" for x, y in parsed_waypoints)
    strategy_text = " | ".join(mllm_info["strategies"])

    return {
        "run_folder": result_folder_name,
        "episode_id": episode_id,
        "agent": agent,
        "mllm": mllm,
        "label": label,
        "success": success,
        "termination": termination,
        "n_steps": n_steps,
        "n_path_points": n_path_points,
        "n_waypoints": n_waypoints,
        "n_waypoints_from_history": n_waypoints_from_history,
        "n_waypoints_from_response": n_waypoints_from_response,
        "n_mllm_calls": mllm_info["n_mllm_calls"],
        "generated_waypoints": waypoint_text,
        "strategies": strategy_text,
        "final_distance_to_target": final_distance_to_target,
        "start_x": start_x,
        "start_y": start_y,
        "start_z": start_z,
        "final_x": final_x,
        "final_y": final_y,
        "final_z": final_z,
        "target_x": target_x,
        "target_y": target_y,
        "target_z": target_z,
    }


def analyze_results(results_dir, run_folder=None, failures_only=False, mllm_only=False):
    """
    Analyze all episodes in all result folders.
    """
    rows = []

    for result_folder in sorted(results_dir.iterdir()):
        if not result_folder.is_dir():
            continue

        if run_folder is not None and result_folder.name != run_folder:
            continue

        episodes_path = result_folder / "episodes.p"
        episodes = load_pickle(episodes_path)

        if episodes is None:
            continue

        for episode_id, episode in get_episode_items(episodes):
            row = summarize_episode(result_folder.name, episode_id, episode)

            if failures_only and row["success"]:
                continue

            if mllm_only and row["n_mllm_calls"] == 0:
                continue

            rows.append(row)

    return rows


def print_summary(rows):
    """
    Print a short summary of the analyzed episodes.
    """
    if not rows:
        print("No episodes found.")
        return

    total = len(rows)
    successes = sum(1 for row in rows if row["success"])
    failures = total - successes
    with_mllm_calls = sum(1 for row in rows if row["n_mllm_calls"] > 0)
    with_waypoints = sum(1 for row in rows if row["n_waypoints"] > 0)

    avg_steps_values = [
        row["n_steps"]
        for row in rows
        if isinstance(row["n_steps"], int)
    ]

    avg_distance_values = [
        row["final_distance_to_target"]
        for row in rows
        if isinstance(row["final_distance_to_target"], (int, float))
    ]

    avg_steps = (
        round(sum(avg_steps_values) / len(avg_steps_values), 2)
        if avg_steps_values
        else "N/A"
    )

    avg_final_distance = (
        round(sum(avg_distance_values) / len(avg_distance_values), 2)
        if avg_distance_values
        else "N/A"
    )

    print()
    print("Episode Analysis Summary")
    print("------------------------")
    print(f"Total episodes:              {total}")
    print(f"Successes:                   {successes}")
    print(f"Failures:                    {failures}")
    print(f"Success rate:                {round(100 * successes / total, 2)}%")
    print(f"Episodes with MLLM calls:    {with_mllm_calls}")
    print(f"Episodes with waypoints:     {with_waypoints}")
    print(f"Average steps:               {avg_steps}")
    print(f"Average final distance:      {avg_final_distance}")
    print()


def print_table(rows, max_rows=30):
    """
    Print a compact per-episode table.
    """
    if not rows:
        return

    print(
        f"{'Run Folder':45} "
        f"{'EpID':6} "
        f"{'Success':8} "
        f"{'Termination':20} "
        f"{'Steps':8} "
        f"{'MLLM':6} "
        f"{'WP':5} "
        f"{'FinalDist':10}"
    )

    print("-" * 120)

    for row in rows[:max_rows]:
        print(
            f"{row['run_folder'][:45]:45} "
            f"{str(row['episode_id'])[:6]:6} "
            f"{str(row['success'])[:8]:8} "
            f"{str(row['termination'])[:20]:20} "
            f"{str(row['n_steps'])[:8]:8} "
            f"{str(row['n_mllm_calls'])[:6]:6} "
            f"{str(row['n_waypoints'])[:5]:5} "
            f"{str(row['final_distance_to_target'])[:10]:10}"
        )

    if len(rows) > max_rows:
        print(f"... showing first {max_rows} of {len(rows)} episodes")


def write_csv(rows, output_path):
    """
    Save episode analysis to CSV.
    """
    if not rows:
        print("No rows to write.")
        return

    fieldnames = [
        "run_folder",
        "episode_id",
        "agent",
        "mllm",
        "label",
        "success",
        "termination",
        "n_steps",
        "n_path_points",
        "n_waypoints",
        "n_waypoints_from_history",
        "n_waypoints_from_response",
        "n_mllm_calls",
        "generated_waypoints",
        "strategies",
        "final_distance_to_target",
        "start_x",
        "start_y",
        "start_z",
        "final_x",
        "final_y",
        "final_z",
        "target_x",
        "target_y",
        "target_z",
    ]

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Saved episode analysis CSV to: {output_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Analyze individual OmniNaviPy evaluation episodes."
    )

    parser.add_argument(
        "--results-dir",
        type=Path,
        default=DEFAULT_RESULTS_DIR,
        help="Path to the folder containing evaluation result folders.",
    )

    parser.add_argument(
        "--run-folder",
        type=str,
        default=None,
        help="Optional single result folder name to analyze.",
    )

    parser.add_argument(
        "--csv",
        type=Path,
        default=None,
        help="Optional path to save per-episode analysis as a CSV file.",
    )

    parser.add_argument(
        "--failures-only",
        action="store_true",
        help="Only show failed episodes.",
    )

    parser.add_argument(
        "--mllm-only",
        action="store_true",
        help="Only show episodes where the MLLM was called.",
    )

    parser.add_argument(
        "--max-rows",
        type=int,
        default=30,
        help="Maximum number of episode rows to print in the terminal.",
    )

    args = parser.parse_args()

    if not args.results_dir.exists():
        print(f"Results folder not found: {args.results_dir}")
        return

    if not args.results_dir.is_dir():
        print(f"Results path is not a folder: {args.results_dir}")
        return

    rows = analyze_results(
        args.results_dir,
        run_folder=args.run_folder,
        failures_only=args.failures_only,
        mllm_only=args.mllm_only,
    )

    print_summary(rows)
    print_table(rows, max_rows=args.max_rows)

    if args.csv:
        write_csv(rows, args.csv)


if __name__ == "__main__":
    main()