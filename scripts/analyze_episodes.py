def main():
    parser = argparse.ArgumentParser(
        description="Analyze individual OmniNaviPy evaluation episodes."
    )

    parser.add_argument(
        "--results-dir",
        type=Path,
        default=DEFAULT_RESULTS_DIR,
        help="Path to the folder containing evaluation result folders.",
    )

    parser.add_argument(
        "--run-folder",
        type=str,
        default=None,
        help="Optional single result folder name to analyze.",
    )

    parser.add_argument(
        "--csv",
        type=Path,
        default=None,
        help="Optional path to save per-episode analysis as a CSV file.",
    )

    parser.add_argument(
        "--waypoint-csv",
        type=Path,
        default=None,
        help="Optional path to save per-waypoint outcome analysis as a CSV file.",
    )

    parser.add_argument(
        "--failures-only",
        action="store_true",
        help="Only show failed episodes.",
    )

    parser.add_argument(
        "--mllm-only",
        action="store_true",
        help="Only show episodes where the MLLM was called.",
    )

    parser.add_argument(
        "--waypoint-threshold",
        type=float,
        default=DEFAULT_WAYPOINT_THRESHOLD,
        help="Distance threshold used to count a generated waypoint as reached.",
    )

    parser.add_argument(
        "--near-threshold",
        type=float,
        default=DEFAULT_NEAR_REPEAT_THRESHOLD,
        help="Distance threshold used to count near-repeated waypoints.",
    )

    parser.add_argument(
        "--max-rows",
        type=int,
        default=30,
        help="Maximum number of episode rows to print in the terminal.",
    )

    parser.add_argument(
        "--max-waypoint-rows",
        type=int,
        default=40,
        help="Maximum number of waypoint rows to print in the terminal.",
    )

    parser.add_argument(
        "--show-waypoints",
        action="store_true",
        help="Print a detailed per-waypoint outcome table.",
    )

    args = parser.parse_args()

    if not args.results_dir.exists():
        print(f"Results folder not found: {args.results_dir}")
        return

    if not args.results_dir.is_dir():
        print(f"Results path is not a folder: {args.results_dir}")
        return

    rows, waypoint_rows = analyze_results(
        args.results_dir,
        run_folder=args.run_folder,
        failures_only=args.failures_only,
        mllm_only=args.mllm_only,
        waypoint_threshold=args.waypoint_threshold,
        near_threshold=args.near_threshold,
    )

    print_summary(rows)
    print_table(rows, max_rows=args.max_rows)

    if args.show_waypoints:
        print_waypoint_table(waypoint_rows, max_rows=args.max_waypoint_rows)

    if args.csv:
        write_csv(rows, args.csv)

    if args.waypoint_csv:
        write_waypoint_csv(waypoint_rows, args.waypoint_csv)


if __name__ == "__main__":
    main()