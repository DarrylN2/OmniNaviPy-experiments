import argparse
import csv
import json
import pickle
from pathlib import Path


DEFAULT_RESULTS_DIR = Path("ignore/results")


def parse_folder_name(folder_name):
    """
    Extract the agent name and MLLM name from a result folder name.

    Example:
    Agent_DataMap__MLLM_None
    becomes:
    agent = DataMap
    mllm = None
    """
    parts = folder_name.split("__")

    agent = "Unknown"
    mllm = "Unknown"

    for part in parts:
        if part.startswith("Agent_"):
            agent = part.replace("Agent_", "")
        elif part.startswith("MLLM_"):
            mllm = part.replace("MLLM_", "")

    return agent, mllm


def load_json(path):
    """
    Safely load a JSON file.
    If the file cannot be read, return an empty dictionary.
    """
    try:
        with open(path, "r") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return {}


def count_episodes(episodes_path):
    """
    Count how many episodes are saved in episodes.p.

    Note:
    This should only be used on pickle files generated by this project.
    """
    if not episodes_path.exists():
        return "N/A"

    try:
        with open(episodes_path, "rb") as f:
            episodes = pickle.load(f)

        return len(episodes)
    except Exception:
        return "N/A"


def yes_no(value):
    """
    Convert True/False into a cleaner table value.
    """
    return "Yes" if value else "No"


def summarize_results(results_dir):
    """
    Read each result folder and collect useful summary information.
    """
    rows = []

    for result_folder in sorted(results_dir.iterdir()):
        if not result_folder.is_dir():
            continue

        metrics_path = result_folder / "metrics.json"
        episodes_path = result_folder / "episodes.p"
        image_path = result_folder / "image_display.png"
        checkpoints_path = result_folder / "checkpoints"

        agent, mllm = parse_folder_name(result_folder.name)

        metrics = {}
        status = "Complete"

        if metrics_path.exists():
            metrics = load_json(metrics_path)
            if not metrics:
                status = "Invalid metrics.json"
        else:
            status = "Missing metrics.json"

        accuracy = metrics.get("accuracy", "N/A")
        episode_count = count_episodes(episodes_path)

        has_image = image_path.exists()
        has_checkpoints = checkpoints_path.exists()

        rows.append(
            {
                "folder": result_folder.name,
                "agent": agent,
                "mllm": mllm,
                "accuracy": accuracy,
                "episodes": episode_count,
                "has_image": yes_no(has_image),
                "has_checkpoints": yes_no(has_checkpoints),
                "status": status,
            }
        )

    return rows


def print_table(rows):
    """
    Print the collected results as a table.
    """
    if not rows:
        print("No result folders were found.")
        return

    print(
        f"{'Folder':40} "
        f"{'Agent':16} "
        f"{'MLLM':14} "
        f"{'Accuracy':10} "
        f"{'Episodes':10} "
        f"{'Image':8} "
        f"{'Checkpoints':12} "
        f"{'Status':20}"
    )

    print("-" * 140)

    for row in rows:
        print(
            f"{row['folder']:40} "
            f"{row['agent']:16} "
            f"{row['mllm']:14} "
            f"{str(row['accuracy']):10} "
            f"{str(row['episodes']):10} "
            f"{row['has_image']:8} "
            f"{row['has_checkpoints']:12} "
            f"{row['status']:20}"
        )


def write_csv(rows, output_path):
    """
    Save the collected results to a CSV file.
    """
    if not rows:
        print("No rows to write.")
        return

    fieldnames = [
        "folder",
        "agent",
        "mllm",
        "accuracy",
        "episodes",
        "has_image",
        "has_checkpoints",
        "status",
    ]

    with open(output_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Saved CSV summary to: {output_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Summarize OmniNaviPy evaluation results."
    )

    parser.add_argument(
        "--results-dir",
        type=Path,
        default=DEFAULT_RESULTS_DIR,
        help="Path to the folder containing evaluation result folders.",
    )

    parser.add_argument(
        "--csv",
        type=Path,
        default=None,
        help="Optional path to save the summary as a CSV file.",
    )

    args = parser.parse_args()

    if not args.results_dir.exists():
        print(f"Results folder not found: {args.results_dir}")
        return

    if not args.results_dir.is_dir():
        print(f"Results path is not a folder: {args.results_dir}")
        return

    rows = summarize_results(args.results_dir)
    print_table(rows)

    if args.csv:
        write_csv(rows, args.csv)


if __name__ == "__main__":
    main()